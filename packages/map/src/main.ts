function refreshDots() {
  if (!state.file) return;
  const f = filters();
  state.byPlace = groupByPlace(state.file, f);
  const dots: Dot[] = [];
  for (const [index, items] of state.byPlace) {
    const p = state.file.places[index];
    const tier = Math.min(...items.map((it) => tierOf(it, state.tiered)));
    dots.push({ index, lon: p.lon, lat: p.lat, count: items.length, weight: weightOf(items), fresh: items[0].t >= f.to - 3600, tier });
  }
  map.setDots(dots);
  map.setPinned(pinnedIndices());
}

// ---- local stories in tiles (decision 78) -------------------------------------

const TILE_RETRY_MS = 60_000;
let tileTimer = 0;
let tileCheckedAt = 0;

/**
 * Looks for tiles that came into view at most a few times a second. A pending look is never pushed back, since the
 * designs that move on their own draw a frame many times a second even while the map holds still.
 */
function tilesSoon() {
  if (!state.file?.local || tileTimer) return;
  const wait = Math.max(150, 400 - (performance.now() - tileCheckedAt));
  tileTimer = window.setTimeout(() => {
    tileTimer = 0;
    loadTilesInView();
  }, wait);
}

/**
 * Loads the tiles of local stories in view, once the map is zoomed in to where they show (the last zoom step, as
 * every GDELT story sits in the lowest tier). The page never waits for them: the day's file is already drawn, and
 * each batch of tiles joins the map when it arrives. Loaded tiles stay, so panning back costs nothing.
 */
function loadTilesInView() {
  tileCheckedAt = performance.now();
  const file = state.file;
  const index = file?.local;
  if (!file || !index) return;
  // Also for a day without zoom tiers, so a whole world of tiles never loads at once.
  if (map.level() < TIERS - 1) return;
  const wanted: string[] = [];
  for (const key of Object.keys(index.tiles)) {
    const seen = state.tiles.get(key);
    if (seen === "loading" || seen === "loaded" || (typeof seen === "number" && tileCheckedAt - seen < TILE_RETRY_MS)) continue;
    const cell = tileCell(key, index.deg);
    if (cell && map.cellInView(cell.south, cell.west, cell.north, cell.east)) wanted.push(key);
  }
  if (!wanted.length) return;
  for (const key of wanted) state.tiles.set(key, "loading");
  Promise.all(
    wanted.map(async (key): Promise<MapTile | null> => {
      const url = tileUrl(BASE, index, key);
      try {
        const res = url ? await fetch(url) : null;
        if (!res?.ok) throw new Error(String(res?.status));
        const tile = (await res.json()) as MapTile;
        state.tiles.set(key, "loaded");
        return tile;
      } catch {
        state.tiles.set(key, performance.now());
        return null;
      }
    }),
  ).then((tiles) => {
    if (state.file !== file) return;
    const added = mergeTiles(file, state.placeIds, tiles.filter((t): t is MapTile => t !== null));
    const failed = tiles.includes(null);
    if (!added && !failed) return;
    if (added) {
      refreshDots();
      renderTicker();
      syncTranslate();
      renderPins();
      refreshChannels();
    }
    // The idle list too, so a failed load is said even where no place is tuned yet.
    if (!state.reader && !state.telegram && !state.event) renderPanel();
  });
}

/** A line under the list while a tile of local stories failed in the last minute; it is asked for again after that. */
function tileNote(): HTMLElement | null {
  const now = performance.now();
  const failed = [...state.tiles.values()].some((v) => typeof v === "number" && now - v < TILE_RETRY_MS);
  return failed ? h("p", { class: "count" }, "Some local stories couldn't load. The map tries again in a minute.") : null;
}

/** A place by id, or by the point its id names when it lives in a tile not loaded yet (a pin, or a shared link). */
function flyToId(id: string): boolean {
  const idx = state.placeIds.get(id);
  if (idx !== undefined) {
    flyToPlace(idx);
    return true;
  }
  const m = /^ll:(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)$/.exec(id);
  if (!m || !state.file?.local) return false;
  const [lat, lon] = [Number(m[1]), Number(m[2])];
  if (Math.abs(lat) > 90 || Math.abs(lon) > 180) return false;
  // Local stories show only at the closest zoom, so land there; the tile loads and the place is tuned as it lands.
  map.flyTo(lon, lat, map.levelZoom(TIERS - 1));
  return true;
}

function pinnedIndices(): number[] {
  if (!state.file) return [];
  const ids = new Set(state.pins.map((p) => p.id));
  return state.file.places.flatMap((p, i) => (ids.has(p.id) ? [i] : []));
}

// ---- what is new at pinned places since the reader's last look -----------------------

/** The map's own clock for a look: the end of the reports on show (the day's file, or the replay's moment). */
const lookTime = () => filters().to;

/**
 * How many reports came out at each pinned place since the reader last looked there, by pin id: the day's window with
 * the topics on, as the place's panel lists them. A town's local stories count once their tile is loaded for the map;
 * no tile is loaded just to count.
 */
function pinNews(): Map<string, number> {
  const out = new Map<string, number>();
  const file = state.file;
  if (!file) return out;
  const seen = new Map<number, number>();
  for (const p of state.pins) {
    const i = state.placeIds.get(p.id);
    if (i !== undefined && p.seen !== undefined) seen.set(i, p.seen);
  }
  if (!seen.size) return out;
  const f = filters(true);
  const counts = newCounts(
    file.items.filter((it) => seen.has(it.place) && passes(it, f)),
    seen,
  );
  for (const p of state.pins) {
    const n = counts.get(state.placeIds.get(p.id) ?? -1);
    if (n) out.set(p.id, n);
  }
  return out;
}

/** The pinned place whose panel is open and its last look before this one, so its "New" marks stay while it is open. */
let look: { id: string; since: number | undefined } | null = null;
let lookTimer = 0;
const LOOK_MS = 1500;

/**
 * The open place's last look before this one, when it is pinned. The first time its panel shows, a look begins; it
 * counts once the place has stayed open a moment, so dragging past a pinned place doesn't use up what is new there.
 */
function lookAt(id: string | null): number | undefined {
  const pin = id === null ? undefined : state.pins.find((p) => p.id === id);
  if (!pin) {
    look = null;
    clearTimeout(lookTimer);
    return undefined;
  }
  if (look?.id !== pin.id) {
    look = { id: pin.id, since: pin.seen };
    clearTimeout(lookTimer);
    lookTimer = window.setTimeout(() => {
      const idx = state.placeIds.get(pin.id);
      if (look?.id !== pin.id || idx === undefined || state.tuned?.length !== 1 || state.tuned[0] !== idx) return;
      state.pins = markSeen(state.pins, pin.id, lookTime());
      savePins(state.pins);
      renderPins();
      refreshChannels();
    }, LOOK_MS);
  }
  return look.since;
}

function flyToPlace(index: number) {
  const p = state.file?.places[index];
  if (p) map.flyTo(p.lon, p.lat);
}

