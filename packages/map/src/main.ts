/** A short line over the map when it can't draw (the basemap failed); null removes it. */
function mapNote(text: string | null) {
  const old = document.getElementById("map-note");
  if (!text) return old?.remove();
  const note = old ?? $("map").appendChild(h("p", { id: "map-note", class: "map-note", role: "status" }));
  note.textContent = text;
}

/** The key opens beside the map, over the panel on a wide screen and as a sheet at the bottom of a phone. */
function setKey(open: boolean) {
  $("key-pop").hidden = !open;
  $("key-btn").setAttribute("aria-expanded", String(open));
}

/**
 * On a phone About is a "?" in the masthead's corner, so the toolbar row holds the four controls. Dual Screen keeps it
 * with the other buttons on the handheld's lower half.
 */
function placeAbout() {
  if (phone.matches && state.theme !== "dual") $("masthead").append($("about-btn"));
  else $("toolbar").append($("about-btn"));
}

function bindGlobal() {
  placeAbout();
  phone.addEventListener("change", () => {
    placeAbout();
    renderToolbar();
  });
  $("zoom-in").addEventListener("click", () => map.zoomBy(1.6));
  $("zoom-out").addEventListener("click", () => map.zoomBy(1 / 1.6));
  $("key-btn").addEventListener("click", () => {
    closeMenus();
    setKey($("key-pop").hidden);
  });
  $("key-close").addEventListener("click", () => {
    setKey(false);
    $("key-btn").focus();
  });
  $("about-btn").addEventListener("click", () => {
    closeMenus();
    setKey(false);
    ($("about") as HTMLDialogElement).showModal();
  });
  ($("translate") as HTMLSelectElement).addEventListener("change", (e) => {
    state.translateTo = normalizeLanguage((e.target as HTMLSelectElement).value);
    setPref("translate", state.translateTo ?? "off");
    renderToolbar();
    renderPanel();
  });
  document.addEventListener("keydown", (e) => {
    const target = e.target as HTMLElement;
    if (target.closest("input, textarea, select, dialog")) return;
    if (e.key === "Escape" && !$("key-pop").hidden) {
      setKey(false);
      $("key-btn").focus();
    } else if (e.key === "Escape" && (state.event || state.telegram || state.reader)) {
      if (state.event) state.event = null;
      else if (state.telegram) closeTelegram();
      else closeReader();
      applyHighlight();
      renderPanel();
    } else if (e.key === "s" || e.key === "S") {
      spin();
    }
  });
  // Close open menus when clicking elsewhere.
  document.addEventListener("click", (e) => {
    // composedPath is fixed at dispatch, so it still holds chips that re-rendered mid-click.
    const path = e.composedPath();
    for (const d of document.querySelectorAll<HTMLDetailsElement>("details.menu[open]")) {
      if (!path.includes(d)) d.open = false;
    }
    if (!$("key-pop").hidden && !path.includes($("key-pop")) && !path.includes($("key-btn"))) setKey(false);
  });
}

async function start() {
  // Kept in step with index.html's <title>, which is what link previews and search results read.
  document.title = `${SITE_NAME}: ${SITE_TAGLINE}`;
  for (const el of document.querySelectorAll("[data-site-name]")) el.textContent = SITE_NAME;
  document.documentElement.dataset.theme = state.theme;
  // Every design's chrome hangs on this attribute. A host page that wraps the site may set its own (a light or dark
  // mode), which would strip the chrome, so it is put back; a few times at most, so two pages can never trade it forever.
  let restores = 0;
  new MutationObserver(() => {
    const root = document.documentElement;
    if (root.dataset.theme !== state.theme && restores++ < 20) root.dataset.theme = state.theme;
  }).observe(document.documentElement, { attributes: true, attributeFilter: ["data-theme"] });
  renderMasthead();
  renderToolbar();
  renderKey();
  renderTelegramStrip();
  renderPanel();
  bindTimebar();
  bindGlobal();
  mountExtras({
    theme: () => state.theme,
    tuned: () => (state.file && state.tuned ? state.tuned.map((i) => state.file!.places[i]?.name ?? "") : null),
    center: () => map.center(),
    latest: () =>
      [...state.byPlace.values()]
        .flat()
        .sort((a, b) => b.t - a.t)
        .slice(0, 5)
        .map((it) => ({ place: state.file!.places[it.place]?.name ?? "", title: it.title, open: () => openReader(it) })),
    builtAt: () => state.file?.generatedAt ?? null,
    kmPerPixel: () => map.kmPerPixel(),
  });
  mountChannels({
    theme: () => state.theme,
    word: () => {
      const file = state.file;
      if (!file) return null;
      const status = wordStatus(file);
      const date = formatRunDate(status.date);
      return file.telegram ? { kicker: status.note ? "Latest Word" : "Today's Word", word: file.telegram.word, date } : { none: "No word for this day", date };
    },
    latest: () => {
      const it = newest();
      return it && state.file ? [h("span", { class: "x-ch-place" }, state.file.places[it.place]!.name), headline(it), metaLine(it, state.file.generatedAt)] : null;
    },
    topics: () => (state.topics.size === FILTERS.length ? "All topics" : `${state.topics.size} of ${FILTERS.length} topics`),
    pins: () => state.pins.map((p) => p.name),
    open: openChannel,
    about: () => ($("about") as HTMLDialogElement).showModal(),
  });

  // Either basemap draws the land; only when neither has does the map say so, rather than show an empty sea.
  let landDrawn = false;
  loadLow(BASE)
    .then((low) => {
      landDrawn = true;
      mapNote(null);
      map.setBasemap(low);
    })
    .catch((e) => {
      console.warn("Basemap failed to load", e);
      if (!landDrawn) mapNote("The coastlines couldn't load. Reload the page to try again.");
    });
  loadHigh(BASE)
    .then(({ map: high, relief }) => {
      landDrawn = true;
      mapNote(null);
      map.setBasemap(undefined, high, relief);
    })
    .catch((e) => console.warn("Detailed basemap failed to load", e));

  try {
    state.file = await loadNews(BASE);
  } catch (err) {
    const first = err instanceof Error && err.message === NO_DAY_YET;
    // The strip would otherwise say "Loading the word..." for good.
    $("telegram").replaceChildren(h("div", { class: "telegram-side" }, h("span", { class: "telegram-note" }, first ? "No word yet" : "The word couldn't be loaded")));
    $("panel").replaceChildren(
      h("p", { class: "pad" }, first ? "The first map isn't ready yet. It appears after the day's run, which starts just after midnight UTC." : "The news couldn't be loaded. Try again in a few minutes."),
    );
    return;
  }
  state.stories = storyIndex(state.file);
  state.tiered = hasTiers(state.file);
  state.file.places.forEach((p, i) => state.placeIds.set(p.id, i));
  if (state.file.source !== "live") {
    const banner = $("banner");
    banner.hidden = false;
    banner.textContent =
      state.file.source === "demo"
        ? (state.file.note ?? "Demo: real headlines, collected outside the daily update.")
        : "Sample: fictional outlets and places. Not real news.";
  }
  refreshDots();
  renderTelegramStrip();
  renderMasthead();
  renderTimeLabel();
  renderTicker();
  renderPanel();

  // A shared link lands on its place, even one whose local stories load only when zoomed in.
  const start = params.get("place");
  const landed = !!start && flyToId(start);
  // Like a radio dial: the map turns on its own until a place lands under the cross.
  if (!landed && !reducedMotion) {
    // A different stretch of the world each visit, a little north of the equator where most places are.
    map.setCenter(Math.random() * 360 - 180, 18);
    map.startSpin();
    renderCard();
  }
  armIdleSpin();
  refreshChannels();
}

start();
